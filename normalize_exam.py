OPT_LETTERS = "กขคงจฉชฌญ"


def count(text, pat):
    return len(re.findall(pat, text))


def main():
    dry = "--dry-run" in sys.argv
    data = json.load(open(PATH))
    total = {p: 0 for p, _ in RULES}
    changed = 0
    for q in data:
        for field in ("question",):
            for p, r in RULES:
                n = count(q[field], p)
                total[p] += n
                q[field] = re.sub(p, r, q[field])
        opts = []
        for o in q["options"]:
            for p, r in RULES:
                n = count(o, p)
                total[p] += n
                o = re.sub(p, r, o)
            opts.append(o)
        q["options"] = opts
        changed += 1
    # verify option letters intact + answers valid
    bad_letters = 0
    for q in data:
        letters = [o.strip()[:1] for o in q["options"]]
        if not all(c in OPT_LETTERS for c in letters):
            bad_letters += 1
    print("questions processed:", len(data))
    print("option-letter anomalies:", bad_letters)
    nz = [(p, c) for p, c in total.items() if c]
    nz.sort(key=lambda x: -x[1])
    print("total fixes:", sum(total.values()))
    for p, c in nz:
        print(f"  {c:4d}  {p} -> {dict(RULES)[p]}")
    if not dry:
        shutil.copyfile(PATH, PATH + ".bak")
        json.dump(data, open(PATH, "w"), ensure_ascii=False, indent=1)
        print("written:", PATH)


main()
